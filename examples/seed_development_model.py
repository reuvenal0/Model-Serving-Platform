"""Seed persistent development data using the same Settings as the API server."""

from pathlib import Path
import pickle
import re

import numpy as np
from sklearn.linear_model import LinearRegression
from sqlalchemy.engine import make_url

from app.config import Settings
from app.core.container import ServiceContainer
from app.core.exceptions import ModelNotFoundError, ModelVersionNotFoundError
from app.domain.enums import DeploymentStatus, ModelFramework, ModelVersionStatus
from app.domain.resource_config import ResourceConfig

MODEL_NAME = "demo-linear"
VERSION = "v1"
DEPLOYMENT_ID = "demo-api-deployment"
DESCRIPTION = "Locally generated development LinearRegression: y = 2*x + 1"
INPUT_SCHEMA = {"inference": {"shape": [None, 1], "dtype": "number"}}
OUTPUT_SCHEMA = {"inference": {"shape": [None], "dtype": "number"}}


def trusted_artifact() -> bytes:
    """Create known trusted bytes; never deserialize an existing artifact here."""
    x = np.array([[1.0], [2.0], [3.0]], dtype=np.float64)
    y = np.array([3.0, 5.0, 7.0], dtype=np.float64)
    estimator = LinearRegression().fit(x, y)
    return pickle.dumps(estimator, protocol=pickle.HIGHEST_PROTOCOL)


def database_path(settings: Settings) -> Path:
    url = make_url(settings.database_url)
    if (url.get_backend_name() != "sqlite" or not url.database
            or url.database == ":memory:" or url.database.startswith("file:")
            or str(url.query.get("mode", "")) == "memory"):
        raise ValueError("Seeding requires a persistent, ordinary SQLite file URL")
    return Path(url.database).resolve()


def seed(settings: Settings) -> str:
    """Run once at a time, with trusted private storage and no concurrent writers.

    Existing bytes must exactly match this environment's freshly trained Pickle.
    Dependency upgrades may change bytes; mismatches require operator inspection,
    never automatic overwrite or deserialization. Only this demo is revalidated.
    """
    location = database_path(settings)
    if not settings.trust_sklearn_artifacts:
        raise ValueError("Set TRUST_SKLEARN_ARTIFACTS=true for both the seed and server processes")
    print("SQLite database:", location)
    print("Artifact storage root:", settings.artifact_storage_dir.resolve())
    expected = trusted_artifact()
    with ServiceContainer(settings) as container:
        registry = container.model_registry
        try:
            model = registry.get_model(MODEL_NAME)
        except ModelNotFoundError:
            model = registry.register_model(MODEL_NAME, DESCRIPTION)
        if model.description != DESCRIPTION:
            raise ValueError("Existing demo model description differs; nothing will be overwritten")
        try:
            version = registry.get_version(MODEL_NAME, VERSION)
        except ModelVersionNotFoundError:
            version = registry.register_version(
                MODEL_NAME, VERSION, ModelFramework.SKLEARN, expected,
                input_schema=INPUT_SCHEMA, output_schema=OUTPUT_SCHEMA,
            )
        if (version.framework is not ModelFramework.SKLEARN
                or version.status is not ModelVersionStatus.REGISTERED
                or version.input_schema != INPUT_SCHEMA or version.output_schema != OUTPUT_SCHEMA):
            raise ValueError("Existing demo version metadata differs; refusing to load or overwrite it")
        if registry.download_artifact(MODEL_NAME, VERSION) != expected:
            raise ValueError("Existing artifact differs from locally generated bytes; refusing to deserialize it")

        manager = container.deployment_manager
        deployments = manager.list_deployments()
        family = [item for item in deployments if re.fullmatch(
            re.escape(DEPLOYMENT_ID) + r"(?:-[2-9]|-[1-9][0-9]+)?", item.id,
        )]
        for item in family:
            if (item.model_name != MODEL_NAME or item.version != VERSION
                    or item.resources != ResourceConfig(1, 128) or item.replicas != 1
                    or item.endpoint is not None):
                raise ValueError(f"Deployment ID {item.id!r} has different configuration; inspect it manually")
            print("Existing deployment:", item.id, item.status.value)
        running = sorted(
            (item for item in family if item.status is DeploymentStatus.RUNNING),
            key=lambda item: (item.id != DEPLOYMENT_ID, len(item.id), item.id),
        )
        if running:
            deployment = running[0]
        else:
            occupied = {item.id for item in deployments}
            identifier = DEPLOYMENT_ID
            suffix = 2
            while identifier in occupied:
                identifier = f"{DEPLOYMENT_ID}-{suffix}"
                suffix += 1
            deployment = manager.deploy(
                MODEL_NAME, VERSION, ResourceConfig(1, 128), deployment_id=identifier,
                smoke_inputs=[[4.0], [5.0]],
            )
        health = manager.check_health(deployment.id, smoke_inputs=[[4.0], [5.0]])
        if not health.ready or health.status is not DeploymentStatus.RUNNING:
            raise RuntimeError("Demo deployment did not reach RUNNING readiness")
        runtime = container.runtime_manager.get_runtime(MODEL_NAME, VERSION)
        for inputs, expected_values in [([[4.0]], [9.0]), ([[5.0]], [11.0]),
                                        ([[4.0], [5.0]], [9.0, 11.0])]:
            actual = runtime.predict(inputs)
            np.testing.assert_allclose(actual, expected_values, rtol=1e-8, atol=1e-8)
            print("Prediction:", inputs, "=>", actual.tolist(), "PASS")
        print("Artifact key:", version.artifact_location)
        print("Deployment:", deployment.id, "RUNNING; readiness PASS")
        print("Verify the running server with:")
        print(f"python -m examples.test_live_api --deployment-id {deployment.id}")
        return deployment.id


def main() -> None:
    seed(Settings())
    print("Resources closed; persistent metadata and artifacts retained.")


if __name__ == "__main__":
    main()
