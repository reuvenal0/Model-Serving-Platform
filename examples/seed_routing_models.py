"""Opt-in persistent v2 development model; never change existing v1 or routing."""

import pickle
import re

import numpy as np
from sklearn.linear_model import LinearRegression

from app.config import Settings
from app.core.container import ServiceContainer
from app.core.exceptions import ModelVersionNotFoundError, RoutingNotFoundError
from app.domain.enums import DeploymentStatus, ModelFramework, ModelVersionStatus
from app.domain.resource_config import ResourceConfig
from examples.seed_development_model import (
    DESCRIPTION, INPUT_SCHEMA, MODEL_NAME, OUTPUT_SCHEMA, database_path, trusted_artifact,
)

V2_DEPLOYMENT_ID = 'demo-api-v2-deployment'


def v2_artifact() -> bytes:
    estimator = LinearRegression().fit(np.array([[1.0], [2.0], [3.0]], dtype=np.float64),
                                       np.array([4.0, 7.0, 10.0], dtype=np.float64))
    return pickle.dumps(estimator, protocol=pickle.HIGHEST_PROTOCOL)


def seed(settings: Settings) -> str:
    if not settings.trust_sklearn_artifacts:
        raise ValueError('Set TRUST_SKLEARN_ARTIFACTS=true for both seed and server')
    print('SQLite database:', database_path(settings))
    print('Artifact root:', settings.artifact_storage_dir.resolve())
    with ServiceContainer(settings) as container:
        registry = container.model_registry
        # Require Phase 5 seeding first. Never restart, replace, or create v1 here.
        if registry.get_model(MODEL_NAME).description != DESCRIPTION:
            raise ValueError('Existing v1 model configuration differs')
        for version, expected in [('v1', trusted_artifact()), ('v2', v2_artifact())]:
            try:
                metadata = registry.get_version(MODEL_NAME, version)
            except ModelVersionNotFoundError:
                if version == 'v1':
                    raise
                metadata = registry.register_version(MODEL_NAME, version, ModelFramework.SKLEARN, expected,
                                                      input_schema=INPUT_SCHEMA, output_schema=OUTPUT_SCHEMA)
            if (metadata.framework is not ModelFramework.SKLEARN
                    or metadata.status is not ModelVersionStatus.REGISTERED
                    or metadata.input_schema != INPUT_SCHEMA or metadata.output_schema != OUTPUT_SCHEMA
                    or registry.download_artifact(MODEL_NAME, version) != expected):
                raise ValueError(f'{version} metadata/artifact differs; refusing overwrite or deserialization')
            # At this point only known locally generated bytes can be loaded.
            if version == 'v1':
                running = [item for item in container.deployment_manager.list_deployments(MODEL_NAME)
                           if item.version == 'v1' and item.status is DeploymentStatus.RUNNING]
                if not running:
                    raise ValueError('v1 requires an existing RUNNING deployment; v1 was left unchanged')
                if not container.deployment_manager.check_health(running[0].id).ready:
                    raise ValueError('v1 is not ready')

        manager = container.deployment_manager
        deployments = manager.list_deployments()
        family = [item for item in deployments if re.fullmatch(re.escape(V2_DEPLOYMENT_ID) + r'(?:-[2-9]|-[1-9][0-9]+)?', item.id)]
        for item in family:
            if (item.model_name != MODEL_NAME or item.version != 'v2' or item.resources != ResourceConfig(1, 128)
                    or item.replicas != 1 or item.endpoint is not None):
                raise ValueError(f'Existing deployment {item.id} differs; inspect manually')
        running = sorted((item for item in family if item.status is DeploymentStatus.RUNNING), key=lambda item: (len(item.id), item.id))
        if running:
            deployment = running[0]
        else:
            occupied = {item.id for item in deployments}
            identifier, suffix = V2_DEPLOYMENT_ID, 2
            while identifier in occupied:
                identifier = f'{V2_DEPLOYMENT_ID}-{suffix}'
                suffix += 1
            deployment = manager.deploy(MODEL_NAME, 'v2', ResourceConfig(1, 128), deployment_id=identifier)
        if not manager.check_health(deployment.id).ready:
            raise RuntimeError('v2 deployment is not ready')
        prediction = container.runtime_manager.get_runtime(MODEL_NAME, 'v2').predict([[4.0], [5.0]])
        np.testing.assert_allclose(prediction, [13.0, 16.0], rtol=1e-8, atol=1e-8)
        try:
            routing = container.routing_manager.get_routing_config(MODEL_NAME)
        except RoutingNotFoundError:
            routing = container.routing_manager.configure_routing(MODEL_NAME, {'v1': 90, 'v2': 10}, 0)
            print('Created initial routing allocation.')
        else:
            print('Existing operator routing retained unchanged.')
        print('Routing revision:', routing.revision, 'weights:', dict(routing.config.weights))
        print('v2 deployment:', deployment.id, 'RUNNING; predictions:', prediction.tolist())
        return deployment.id


def main() -> None:
    seed(Settings())
    print('Resources closed; v1 and persistent artifacts retained.')


if __name__ == '__main__':
    main()
